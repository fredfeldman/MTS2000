namespace MTS2000.Core.Protocol;

/// <summary>
/// A fixed 5-byte frame on the radio's control bus (device/address byte, two data bytes, a
/// command byte, and a trailing checksum byte). This bus is used to switch the radio between
/// normal and programming mode and to request its firmware version before the higher-level
/// memory-access protocol takes over.
/// </summary>
public sealed class ControlBusFrame
{
    public byte Device { get; }
    public byte DataA { get; }
    public byte DataB { get; }
    public byte Command { get; }
    public byte Checksum { get; }

    /// <summary>Whether the radio is expected to send a reply frame after this one (beyond the plain echo).</summary>
    public bool ExpectsReply { get; }

    public bool IsMalformed { get; }

    public ControlBusFrame(byte device, byte dataA, byte dataB, byte command, bool expectsReply = false)
    {
        Device = device;
        DataA = dataA;
        DataB = dataB;
        Command = command;
        ExpectsReply = expectsReply;
        Checksum = ComputeChecksum(device, dataA, dataB, command);
    }

    private ControlBusFrame(byte device, byte dataA, byte dataB, byte command, byte receivedChecksum, bool isMalformed)
    {
        Device = device;
        DataA = dataA;
        DataB = dataB;
        Command = command;
        Checksum = receivedChecksum;
        IsMalformed = isMalformed;
    }

    /// <summary>Parses a frame that was just read off the wire, validating its checksum.</summary>
    public static ControlBusFrame? TryParse(ReadOnlySpan<byte> raw)
    {
        if (raw.Length != 5)
        {
            return null;
        }

        var expected = ComputeChecksum(raw[0], raw[1], raw[2], raw[3]);
        return new ControlBusFrame(raw[0], raw[1], raw[2], raw[3], raw[4], isMalformed: expected != raw[4]);
    }

    public byte[] ToWireBytes() => [Device, DataA, DataB, Command, Checksum];

    private static byte ComputeChecksum(byte device, byte dataA, byte dataB, byte command)
    {
        byte crc = ChecksumTable[device];
        crc = ChecksumTable[crc ^ dataA];
        crc = ChecksumTable[crc ^ dataB];
        crc = ChecksumTable[crc ^ command];
        return crc;
    }

